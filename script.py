BASE_URL = (
    "https://en.volleyballworld.com/volleyball/competitions/"
    "volleyball-nations-league/players/"
)

options = uc.ChromeOptions()
options.add_argument("--headless")
driver = uc.Chrome(options=options)
wait = WebDriverWait(driver, 15)


def safe_text(selector, default="-"):
    """Extract stripped text from a DOM element or return a fallback value."""
    try:
        return driver.find_element(By.CSS_SELECTOR, selector).text.strip()
    except NoSuchElementException:
        return default


def scrape_player(player_id):
    """Scrape demographic profile data and match metrics for a single player ID."""
    driver.get(BASE_URL + str(player_id))
    try:
        wait.until(
            EC.presence_of_element_located((By.CSS_SELECTOR, ".vbw-player-name"))
        )
    except TimeoutException:
        print(f"  Timeout: {player_id}")
        return None

    name = safe_text("h1.vbw-player-name")
    team = safe_text("a.player-team-text")
    position = safe_text(
        ".vbw-player-bio-col:nth-child(2) .vbw-player-bio-text.--desktop"
    )
    age = safe_text(".vbw-player-bio-col:nth-child(4) .vbw-player-bio-text")
    height = safe_text(".vbw-player-bio-col:nth-child(6) .vbw-player-bio-text")

    stats = driver.find_elements(By.CSS_SELECTOR, ".vbw-player-stats-text")

    def st(idx):
        return stats[idx].text.strip() if idx < len(stats) else "-"

    return {
        "id": player_id,
        "name": name,
        "team": team,
        "position": position,
        "age": age,
        "height_cm": height.replace("cm", "").strip(),
        "total_points": st(0),
        "avg_per_match": st(1),
        "attack_pts": st(2),
        "attack_eff": st(3),
        "attack_avg": st(4),
        "block_pts": st(5),
        "block_eff": st(6),
        "block_avg": st(7),
        "serve_pts": st(8),
        "serve_eff": st(9),
        "serve_avg": st(10),
    }


players = []
TOTAL = len(PLAYER_IDS)

for i, pid in enumerate(PLAYER_IDS):
    print(f"[{i + 1}/{TOTAL}] {pid}...", end=" ")
    data = scrape_player(pid)
    if data:
        players.append(data)
        print(f"✓ {data['name']} ({data['team']})")
    else:
        print("✗ Error")
    time.sleep(1.5)

driver.quit()

df = pd.DataFrame(players)
df.to_csv("vnl2026_TBD.csv", index=False)
